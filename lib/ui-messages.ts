const templates = Object.entries(messages).filter(([key]) => key.includes('{0}')).map(([key, value]) => ({
  pattern: new RegExp('^' + key.split(/\{\d+\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('([\\s\\S]*?)') + '$'), value,
}));
export function translate(text: string, language: UiLanguage): string {
  if (language === 'zh-CN' || !text.trim()) return text;
  const source = text.trim();
  if (source.includes('\n')) return text.split('\n').map(line => translate(line, language)).join('\n');
  let translated = Object.hasOwn(messages, source) ? messages[source] : undefined;
  if (!translated) {
    for (const { pattern, value } of templates) {
      const match = pattern.exec(source);
      if (match) { translated = value.replace(/\{(\d+)\}/g, (_, index) => translate(match[Number(index) + 1] ?? '', language)); break; }
    }
  }
  const suffix = ' 语言偏好保存失败，请稍后重试。';
  if (!translated && source.endsWith(suffix)) translated = translate(source.slice(0, -suffix.length), language) + ' ' + messages[suffix.trim()];
  return translated ? text.replace(source, () => translated!) : text;
}
